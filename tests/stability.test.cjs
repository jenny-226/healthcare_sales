// Run: node tests/stability.test.cjs (no dependencies)
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.join(__dirname, '..');
const memory = new Map();
const context = vm.createContext({ console, localStorage: { getItem: k => memory.get(k) ?? null, setItem: (k, v) => memory.set(k, v), removeItem: k => memory.delete(k) } });
context.window = context;
const load = file => vm.runInContext(fs.readFileSync(path.join(root, file), 'utf8'), context, { filename: file });
['data/sample-products.js', 'data/sample-cases.js', 'data/packaging-presets.js', 'js/core/dates.js', 'js/core/store.js', 'js/core/ui.js', 'js/services/products.js', 'js/services/cases.js', 'js/services/stability.js'].forEach(load);
const D = context.DASH, S = D.services.stability;
D.store.seedIfNeeded();
const c = { id: 'test', productId: 'P-001', request: { description: '프로바이오틱스 100억 CFU 젤리, 상온 18개월 개별 포장' } };
let v = S.resolve(c).values;
assert.equal(v.targetCFU, 1e10);
assert.equal(v.months, 18);
assert.equal(v.form, 'jelly_stick');
assert.equal(v.temperature, undefined, '상온은 25도로 추정하지 않는다');
assert.equal(S.analyze(c).curve.length, 0);
assert.equal(S.resolve({ productId: 'P-001' }).values.targetCFU, undefined, '처방량을 보장량으로 대입하지 않는다');
c.request.stability = { temperature: 0, aw: 0, months: 12 };
assert.equal(S.resolve(c).values.temperature, 0);
assert.equal(S.resolve(c).values.aw, 0);
assert.equal(S.resolve(c).values.months, 12);
c.stabilityScenario = { months: 18, initialCFU: 1e10, lossRate: 0.1 };
assert.equal(S.analyze(c).curve.length, 19);
assert.ok(Math.abs(S.analyze(c).curve[10].cfu - 1e9) < 1);
assert.equal(S.validate({ aw: 1.01 }).length, 1);
assert.equal(S.validate({ months: 0 }).length, 1);
assert.equal(S.validate({ months: 1.5 }).length, 1);
assert.equal(S.validate({ lossRate: -1 }).length, 1);
assert.equal(S.validate({ temperature: 0, aw: 0, lossRate: 0 }).length, 0);
assert.equal(S.resolve({ request: { description: '100억 CFU 또는 50억 CFU' } }).values.targetCFU, undefined);
assert.equal(S.resolve({ request: { description: '10 billion CFU 18 months 25°C' } }).values.targetCFU, 1e10);
const data = { strains: [{ id: 's1', name: '실제 자료 테스트' }], studies: [{ id: 't1', strainId: 's1', source: '연구소 보고서', form: 'jelly_stick', temperature: 0, aw: 0, packaging: '개별 포장', points: [{ month: 0, cfu: 1e10 }, { month: 18, cfu: 1e9 }] }] };
S.importLibrary(data);
c.request.stability.strainId = 's1';
assert.equal(S.analyze(c).matched.length, 1);
c.stabilityScenario.temperature = 25;
assert.equal(S.analyze(c).matched.length, 0);
assert.equal(S.analyze(c).studies.length, 1);
const invalid = JSON.parse(JSON.stringify(data)); invalid.studies[0].points[0].cfu = -1;
assert.throws(() => S.importLibrary(invalid));
assert.equal(S.library().studies[0].points[0].cfu, 1e10, '불량 입력은 기존 자료를 훼손하지 않는다');
S.importLibrary({ strains: [{ id: 's2', name: '두 번째 균주' }], studies: [] });
assert.equal(S.library().strains.length, 2);
delete c.stabilityScenario;
c.request.stability.months = 24;
assert.equal(S.resolve(c).values.months, 24, '요청서 갱신 반영');
assert.equal(S.resolve({ id: 'other', request: {} }).values.months, undefined, '다른 건 격리');
// Render with minimal DOM handles: catches template/runtime errors and checks escaping.
let tab;
D.registerTab = def => { tab = def; };
load('js/tabs/stability.js');
const handles = new Map();
const el = { innerHTML: '', querySelector: selector => {
  if (!handles.has(selector)) handles.set(selector, { addEventListener() {} });
  return handles.get(selector);
} };
c.request.productName = '<img src=x onerror=alert(1)>';
tab.render(el, c);
assert.ok(el.innerHTML.includes('&lt;img'));
assert.ok(!el.innerHTML.includes('<img src=x'));
assert.ok(el.innerHTML.includes('R&D 검토 필요'));
assert.ok(S.requestFields(c.request).includes('data-stability'));
console.log('Stability assertions passed (linkage, validation, evidence, isolation, rendering).');
